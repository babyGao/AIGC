// 角色几何（与风格无关）：每个角色输出“部件表”，部件 = { id, P: 多边形 | L: 开折线(+w 宽), role, ... }。
// role 决定各风格怎么处理：
//   dark  深色大块（袍、发、兽皮）       mid  中间调（尸体衣袍、远处人群）     skin  皮肤（木刻刻白、水墨淡墨、剪纸骨白）
//   white 白色（衣领、白发、白须）        feat  五官细线 / 褶线（L + w）          accent 唯一的颜色（毛里球的紫、眼睛的红）
//   tooth 牙                              hole  口腔深处 / 张开的嘴
// 坐标：身高 1000 单位，脚底 y=0，向上为负；侧身一律面朝 +x。
import { C, O, xf, ell, ribbon, capsule, spiky, rng } from './geo.js';

const P = (id, P, role, o = {}) => ({ id, P, role, ...o });
const L = (id, L, w, role = 'feat', o = {}) => ({ id, L, w, role, ...o });

