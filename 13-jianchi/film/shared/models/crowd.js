// 远景里的小人：站立的蛊仙（正面或背面），归一化：脚底中点在原点，身高 1（头顶 y = -1）。
// 只在远景用（几十到一两百像素高），细节按身份给：发色、发型、头饰、毛裘、须、袍色。
//   standing(o) → layers；o: { robe:'robe'|'robeD'|'blue'..., hair:'hair'|'hairW', style:'bun'|'long'|'crown', fur, beard, sleeve:'down'|'out'|'point', back }
export function standing(o = {}, T = p => p) {
  const L = [], fill = (role, pts, key) => L.push({ fill: role, pts: pts.map(T), key }), line = (pts, w, dark, key) => L.push({ line: pts.map(T), w: w * (T.s || 1), dark, key });
  const R = o.robe || 'robe', H = o.hair || 'hair';
  // 长发垂在背后（正面时在肩两侧）
  if (o.style === 'long' || o.longHair) fill(H, [[-.065, -.97], [-.1, -.9], [-.14, -.72], [-.16, -.5], [-.15, -.42], [.15, -.42], [.16, -.5], [.14, -.72], [.1, -.9], [.065, -.97]], 'backHair');
  // 毛裘披风（雪胡）
  if (o.fur) fill('fur', [[-.13, -.82], [-.2, -.6], [-.24, -.3], [-.26, 0], [.26, 0], [.24, -.3], [.2, -.6], [.13, -.82], [0, -.84]], 'cloak');
  // 袍：下摆略张开
  fill(R, [[-.07, -.84], [-.12, -.8], [-.14, -.6], [-.16, -.3], [-.2, 0], [.2, 0], [.16, -.3], [.14, -.6], [.12, -.8], [.07, -.84]], 'robe');
  // 袖：下垂 / 张开 / 指人
  const sl = o.sleeve || 'down';
  if (sl === 'down') { fill(R, [[-.12, -.8], [-.2, -.6], [-.23, -.38], [-.15, -.36], [-.12, -.6]], 'slvL'); fill(R, [[.12, -.8], [.2, -.6], [.23, -.38], [.15, -.36], [.12, -.6]], 'slvR'); }
  if (sl === 'out') { fill(R, [[-.12, -.8], [-.3, -.72], [-.42, -.6], [-.36, -.5], [-.2, -.6], [-.12, -.64]], 'slvL'); fill(R, [[.12, -.8], [.3, -.72], [.42, -.6], [.36, -.5], [.2, -.6], [.12, -.64]], 'slvR'); }
  if (sl === 'point') { fill(R, [[-.12, -.8], [-.2, -.6], [-.23, -.38], [-.15, -.36], [-.12, -.6]], 'slvL'); fill(R, [[.12, -.8], [.3, -.8], [.44, -.82], [.44, -.74], [.3, -.7], [.14, -.66]], 'slvR'); fill('skin', [[.44, -.82], [.52, -.8], [.44, -.76]], 'finger'); }
  if (o.belt) fill(o.belt, [[-.13, -.58], [.13, -.58], [.135, -.54], [-.135, -.54]], 'belt');
  // 头
  fill('skin', [[-.05, -.94], [-.055, -.88], [-.04, -.83], [0, -.81], [.04, -.83], [.055, -.88], [.05, -.94], [0, -.96]], 'face');
  if (!o.back) { line([[-.03, -.895], [-.012, -.892]], .006, 1, 'eye'); line([[.012, -.892], [.03, -.895]], .006, 1, 'eye'); }
  if (o.beard) fill(H, [[-.045, -.86], [0, -.84], [.045, -.86], [.03, -.74], [0, -.68], [-.03, -.74]], 'beard');
  // 发
  if (o.style === 'long' && !o.back) { fill(H, [[-.06, -.94], [-.085, -.8], [-.095, -.6], [-.075, -.56], [-.06, -.8]], 'curtainL'); fill(H, [[.06, -.94], [.085, -.8], [.095, -.6], [.075, -.56], [.06, -.8]], 'curtainR'); }
  fill(H, o.back ? [[-.06, -.95], [-.065, -.86], [-.05, -.8], [.05, -.8], [.065, -.86], [.06, -.95], [0, -1]] : [[-.06, -.93], [-.06, -.97], [0, -1.0], [.06, -.97], [.06, -.93], [.03, -.955], [-.03, -.955]], 'cap');
  if (o.style === 'bun' || o.style === 'crown') fill(H, [[-.03, -.99], [-.025, -1.04], [0, -1.05], [.025, -1.04], [.03, -.99]], 'bun');
  if (o.style === 'crown') fill('gold', [[-.045, -1.0], [-.04, -1.07], [0, -1.09], [.04, -1.07], [.045, -1.0]], 'crown');
  return L;
}

// 侧身站立（面朝左），给皮影和需要侧身的镜头用。头用 profile.js 的侧脸生成器（以方源侧脸为底）。
import { profileHead } from './profile.js';
export function sideStanding(o = {}, T = p => p) {
  const L = [], k = T.s || 1, fill = (role, pts, key) => L.push({ fill: role, pts: pts.map(T), key }), line = (pts, w, dark, key) => L.push({ line: pts.map(T), w: w * k, dark, key });
  const R = o.robe || 'robe', H = o.hair || 'hair', hs = .145, chin = [-.01, -.855];
  const HT = p => T([chin[0] + p[0] * hs, chin[1] + p[1] * hs]); HT.s = hs * k;
  const head = (pts) => pts.map(p => [chin[0] + p[0] * hs, chin[1] + p[1] * hs]);
  if (o.style === 'long') fill(H, head([[.3, -.9], [.6, -.7], [.75, -.3], [.82, .4], [.9, 1.6], [.6, 1.7], [.42, .6], [.3, -.1]]), 'backHair');
  if (o.fur) fill('fur', [[.0, -.82], [.12, -.84], [.2, -.7], [.24, -.4], [.28, 0], [-.02, 0], [-.04, -.5]], 'cloak');
  fill(R, [[.0, -.84], [.1, -.85], [.13, -.75], [.14, -.5], [.17, -.2], [.2, 0], [-.13, 0], [-.1, -.2], [-.07, -.45], [-.04, -.7], [-.02, -.8]], 'robe');
  if (o.belt) fill(o.belt, [[-.065, -.52], [.145, -.52], [.145, -.48], [-.07, -.48]], 'belt');
  line([[-.13, 0], [.2, 0]], .004, .8, 'hem');
  const sl = o.sleeve || 'down';
  if (sl === 'down') fill(R, [[.03, -.8], [.1, -.8], [.12, -.6], [.11, -.42], [-.02, -.38], [-.03, -.5], [.0, -.7]], 'sleeve');
  if (sl === 'point') { fill(R, [[.03, -.8], [.1, -.8], [.06, -.72], [-.12, -.7], [-.24, -.72], [-.24, -.66], [-.12, -.6], [.02, -.62]], 'sleeve'); fill('skin', [[-.24, -.71], [-.31, -.7], [-.24, -.67]], 'finger'); }
  if (sl === 'raise') { fill(R, [[.03, -.8], [.1, -.8], [.06, -.86], [-.06, -.98], [-.12, -1.0], [-.1, -.92], [-.02, -.82]], 'sleeve'); }
  line([[.0, -.78], [.0, -.6], [-.01, -.42]], .003, .4, 'fold');
  fill('ink', [[-.12, 0], [-.16, .006], [-.04, .008], [-.02, 0]], 'shoe');
  L.push(...profileHead(HT, o.face || {}));
  const cap = [[-.13, -.7], [-.1, -.88], [.06, -1.0], [.28, -1.05], [.5, -.98], [.64, -.8], [.64, -.56], [.5, -.46], [.38, -.5], [.3, -.64], [.14, -.75], [-.02, -.76]];
  fill(H, head(cap), 'cap');
  if (o.style === 'bun' || o.style === 'crown') fill(H, head([[.2, -1.02], [.24, -1.16], [.36, -1.2], [.46, -1.12], [.44, -1.0]]), 'bun');
  if (o.style === 'crown') fill('gold', head([[.12, -1.04], [.16, -1.22], [.32, -1.28], [.46, -1.2], [.48, -1.04]]), 'crown');
  if (o.beard) fill(H, head([[-.04, -.12], [.08, -.1], [.14, .1], [.1, .5], [.0, .8], [-.06, .3]]), 'beard');
  if (o.circlet) fill('gold', head([[-.1, -.76], [.1, -.86], [.32, -.86], [.32, -.8], [.1, -.8], [-.08, -.71]]), 'circlet');
  return L;
}
