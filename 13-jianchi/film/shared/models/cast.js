// 一绺头发：给中线点列 [x,y,半宽]，生成 {a,b}（发梢收尖）
function lockFromAxis(ax) {
  const a = [], b = [];
  for (let i = 0; i < ax.length; i++) {
    const p = ax[Math.max(0, i - 1)], q = ax[Math.min(ax.length - 1, i + 1)];
    let dx = q[0] - p[0], dy = q[1] - p[1]; const m = Math.hypot(dx, dy) || 1; dx /= m; dy /= m;
    const w = ax[i][2]; a.push([ax[i][0] - dy * w, ax[i][1] + dx * w]); b.push([ax[i][0] + dy * w, ax[i][1] - dx * w]);
  }
  return { a, b };
}
// 由几个控制点插出一条发流中线：pts=[[x,y],...]，w0 根部半宽，w1 末端半宽
function flow(pts, w0, w1 = 0) { return pts.map((p, i) => [p[0], p[1], w0 + (w1 - w0) * (i / (pts.length - 1)) ** 1.2]); }

function bust(o) {
  const T = placer(o.at || [0, 0], o.H || 1, o.flip), M = p => T(p);
  const L = [];
  const fill = (role, pts, key) => L.push({ fill: role, pts: pts.map(M), key });
  const k = (o.H || 1) / 110, line = (pts, w, dark, key) => L.push({ line: pts.map(M), w: w * k, dark, key });
  const lock = (role, ax, strands = 3, sw = .9) => { const lk = lockFromAxis(ax); L.push({ lock: { a: lk.a.map(M), b: lk.b.map(M) }, role, strands, sw: sw * k }); };
  // 1 身后的头发
  (o.backHair || []).forEach(h => lock(o.hairRole || 'hair', h, 4));
  // 2 肩与衣：侧身躯干（胸在前、背斜、肩溜），交领一条带子沿领口绕到胸前
  if (o.robe) {
    const torso = o.robe.pts || [[-.04, .36], [-.14, .46], [-.2, .62], [-.24, .84], [-.26, 1.06], [.78, 1.06], [.76, .84], [.7, .6], [.6, .44], [.48, .36], [.34, .32], [.14, .32]];
    fill(o.robe.role || 'robe', torso, 'robe');
    (o.robe.lines || [[[.2, .5], [.16, .76], [.12, 1.04]], [[.5, .5], [.56, .78], [.6, 1.04]]]).forEach(l => line(l, 1, .55, 'fold'));
    line([[.52, .42], [.6, .56], [.64, .74]], 1, .6, 'shoulder');
  }
  if (o.collar !== false) {
    const band = [[.36, .3], [.2, .32], [.06, .36], [-.06, .44], [-.13, .54], [-.06, .58], [.04, .48], [.16, .41], [.3, .37], [.4, .36]];
    fill((o.collar && o.collar.role) || 'collar', band, 'collar'); line(band, .9, .8, 'collarEdge');
  }
  (o.trim || []).forEach(t => fill(t.role, t.pts, 'trim'));
  (o.trimLines || []).forEach(t => line(t, 1, .8, 'trimEdge'));
  // 3 头
  L.push(...profileHead(T, o.face));
  // 4 头顶、鬓发、刘海
  if (o.cap) { fill(o.hairRole || 'hair', o.cap, 'cap'); (o.capLines || []).forEach(l => line(l, .7, .45, 'hs')); }
  (o.frontHair || []).forEach(h => lock(o.hairRole || 'hair', h, 2, .7));
  (o.extra || []).forEach(e => e.fill ? fill(e.fill, e.pts, e.key) : line(e.line, e.w, e.dark ?? 1, e.key));
  return L;
}

